export const DEVANAGARI_DIGITS = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"] as const;

/**
 * Converts any standard Arabic numeral or string to Devanagari numerals.
 * Example: 2083 -> २०८३, "2083-07-27" -> "२०८३-०७-२७"
 */
export function numberToNe(input: number | string): string {
  return String(input).replace(/[0-9]/g, (digit) => DEVANAGARI_DIGITS[Number(digit)] ?? digit);
}

/**
 * Converts any Devanagari numeral string back to standard ASCII digits.
 * Example: "२०८३-०७-२७" -> "2083-07-27"
 */
export function neToNumber(input: string): string {
  return input.replace(/[०-९]/g, (ch) => {
    const idx = DEVANAGARI_DIGITS.indexOf(ch as (typeof DEVANAGARI_DIGITS)[number]);
    return idx >= 0 ? String(idx) : ch;
  });
}

